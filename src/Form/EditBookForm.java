    private void btnChooseFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnChooseFileActionPerformed
        // TODO add your handling code here:

        JFileChooser filechooser = new JFileChooser();
        filechooser.setDialogTitle("Chọn tệp ảnh của bạn");
        filechooser.setCurrentDirectory(new File(System.getProperty("user.home")));

        FileNameExtensionFilter extensionFilter = new FileNameExtensionFilter("Image", "png", "jpg", "jpeg");
        filechooser.addChoosableFileFilter(extensionFilter);

        int fileState = filechooser.showOpenDialog(this);
        if (fileState == JFileChooser.APPROVE_OPTION) {
            try {
                File selectedFile = filechooser.getSelectedFile();
                this.imagePath = selectedFile.getAbsolutePath(); // Lưu đường dẫn vào biến thành viên

                // Hiển thị đường dẫn
                // Hiển thị ảnh
                func.displayImage(125, 80, null, this.imagePath, jlabel_image);
                jlabel_image.setPreferredSize(new Dimension(125, 80));

                // In ra console để debug
                System.out.println("Selected file path: " + this.imagePath);
                System.out.println("File exists: " + selectedFile.exists());
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Lỗi: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnChooseFileActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:

        // TODO add your handling code here:
        if (!verif()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ", "Lỗi", JOptionPane.WARNING_MESSAGE);
        } else {

            String isbn = jTextField_ISBN.getText();
            String name = jTextField_Name.getText();
            String author_id = jTextField_Author.getText();
            String genre_id = jTextField_Genre.getText();
            String description = jTextField_Description.getText();
            String publisher = jTextField_Publisher2.getText();
            Double price = Double.parseDouble(jTextField_Price.getText());
            Integer quantity = Integer.parseInt(jSpinner_Quantity.getValue().toString());
            String date = jTextField_Publisher1.getText();

            byte[] img = null; // Initialize img with null
            boolean imageChanged = false; // Flag to track if the image has been changed

            // Check if a new image has been selected
            if (this.imagePath != null && !this.imagePath.isEmpty()) {
                try {
                    // Read the new image data
                    Path path = Paths.get(this.imagePath);
                    img = Files.readAllBytes(path);
                    imageChanged = true; // Set the flag to true
                } catch (IOException ex) {
                    Logger.getLogger(EditBookForm.class.getName()).log(Level.SEVERE, null, ex);
                    JOptionPane.showMessageDialog(this, "Lỗi đọc file ảnh: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
                    return; // Exit if there's an error reading the image file
                }
            }

            try {
                // Update book information in the database
                Classes.Book book = new Classes.Book();
                book.updateBook(isbn, name, author_id, genre_id, quantity, publisher, price, date, description, img, imageChanged);

            } catch (Exception ex) {
                Logger.getLogger(EditBookForm.class.getName()).log(Level.SEVERE, null, ex);
                JOptionPane.showMessageDialog(null, "Lỗi: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
            }
        }

    }//GEN-LAST:event_btnEditActionPerformed

