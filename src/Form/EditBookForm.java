    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String tentacpham = txtSearch.getText().trim();
        // Validate the input
        if (tentacpham.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập tên sách.", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Classes.Book selectedBook = book.getBookbyName(tentacpham);
        if (selectedBook != null) {
            // Populate fields with data from the selected book
            jTextField_ISBN.setText(selectedBook.getIsbn());
            jTextField_Name.setText(selectedBook.getName());
            jTextField_Author.setText(selectedBook.getAuthor_id());
            jTextField_Publisher2.setText(selectedBook.getPublisher());
            jTextField_Genre.setText(selectedBook.getGenre_id());
            jTextField_Price.setText(Double.toString(selectedBook.getPrice()));
            jTextField_Publisher1.setText(selectedBook.getDate_receive());
            jTextField_Description.setText(selectedBook.getDescription());
            byte[] image = selectedBook.getCover();
            func.displayImage(125, 80, image, "", jlabel_image);
        } else {
            JOptionPane.showMessageDialog(this, "Không tìm thấy sách với tên đã nhập.", "Thông báo", JOptionPane.WARNING_MESSAGE);
        }

    }//GEN-LAST:event_jButton1ActionPerformed

