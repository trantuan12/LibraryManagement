    private void btnAdd1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdd1ActionPerformed
        // TODO add your handling code here:

        try {
            String bookName = txtBookName.getText().trim();

            if (bookName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập tên tác phẩm cần xóa.", "Thông báo", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int confirm = JOptionPane.showConfirmDialog(this, "Bạn có chắc chắn muốn xóa sách này?", "Xác nhận xóa", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                Classes.Book book = new Classes.Book();
                boolean success = book.deleteBookByName(bookName);

                if (success) {
                    JOptionPane.showMessageDialog(this, "Xóa sách thành công!", "Thông báo", JOptionPane.INFORMATION_MESSAGE);
                    lblBookCover.setIcon(null); // Clear the book cover
                } else {
                    JOptionPane.showMessageDialog(this, "Không thể xóa sách. Vui lòng kiểm tra lại thông tin.", "Lỗi", JOptionPane.ERROR_MESSAGE);
                }
            }
        } catch (SQLException ex) {
            Logger.getLogger(DeleteBook.class.getName()).log(Level.SEVERE, null, ex);
            JOptionPane.showMessageDialog(this, "Lỗi truy vấn: " + ex.getMessage(), "Lỗi", JOptionPane.ERROR_MESSAGE);
        }
        
        
           DashboardForm Dashboard = new DashboardForm();
      Dashboard.dispose();
      openDashBoardForm();
      

    }//GEN-LAST:event_btnAdd1ActionPerformed

