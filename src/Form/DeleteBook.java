    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String bookName = txtBookName.getText().trim();
        if (bookName.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập tên tác phẩm cần tìm.", "Thông báo", JOptionPane.WARNING_MESSAGE);
            return;
        }
        Classes.Book book = new Classes.Book();
        Classes.Book selectedBook = book.getBookbyName(bookName);
        if (selectedBook != null) {
            // Display book cover
            if (selectedBook.getCover() != null) {
                func.displayImage(124, 144, selectedBook.getCover(), null, lblBookCover);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Không tìm thấy sách với tên đã nhập.", "Thông báo", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

